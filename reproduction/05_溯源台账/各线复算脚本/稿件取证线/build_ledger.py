def build():
    os.makedirs(OUT, exist_ok=True)
    # E4 数值改挂到逐条原始判分 grade_r2.json（SHA256 与 E4_scored_records.json 声明一致）
    for r in ROWS:
        if r["cid"] in {"M-E4-01", "M-E4-04", "M-E4-05", "M-E4-06", "M-E4-07", "M-E4-08",
                        "M-E4-09", "M-E4-10", "M-E4-14", "M-E4-15", "S-E4-02"}:
            r["ev"] = "E4_RAW"
            r["cmd"] = C_E4
    ev_sha = {}
    for k, (rel, label) in EV.items():
        if rel is None:
            ev_sha[k] = ""
            continue
        p = os.path.join(ROOT, rel)
        ev_sha[k] = sha(p) if os.path.isfile(p) else "【文件不存在】"

    path = os.path.join(OUT, "溯源表_稿件.csv")
    hdr = ["claim_id", "实验", "论文文件", "论文行号", "论文原文片段", "论文呈现值",
           "证据文件路径", "证据SHA256", "可复现命令", "一致性判定", "来源标签", "备注"]
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(hdr)
        for r in ROWS:
            rel, dlabel = EV[r["ev"]]
            label = r["label"] or dlabel
            w.writerow([r["cid"], r["exp"], r["f"], r["ln"], r["snip"], r["val"],
                        rel if rel else "无证据",
                        ev_sha[r["ev"]] if rel else "无证据",
                        r["cmd"], r["verdict"], label, r["note"]])
    print("rows:", len(ROWS), "->", path)
    c = collections.Counter(r["verdict"] for r in ROWS)
    print("verdict:", dict(c))
    miss = [k for k in EV if EV[k][0] and ev_sha[k] != "" and ev_sha[k].startswith("【")]
    print("missing evidence files:", miss)
    return c


