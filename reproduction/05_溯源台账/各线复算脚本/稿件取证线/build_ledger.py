def read(rel):
    return open(rel, encoding="utf-8").read()


def sha(rel):
    h = hashlib.sha256()
    with open(rel, "rb") as f:
        for c in iter(lambda: f.read(1 << 20), b""):
            h.update(c)
    return h.hexdigest()


